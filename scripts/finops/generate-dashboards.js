#!/usr/bin/env node
/**
 * Generate the FinOps Grafana dashboards and alert rules from the catalogue (spec 089).
 *
 *   npm run finops:generate            write infra/grafana/
 *   npm run finops:generate -- --check exit 1 if the committed tree is stale (used by check:finops)
 *
 * The output is COMMITTED. That is what makes the coverage gate a regenerate-and-diff check — the
 * same shape as this repo's other byte gates — instead of a parser that has to guess at the intent
 * of hand-authored JSON.
 *
 * NEVER hand-edit infra/grafana/. Edit the catalogue or these builders and regenerate.
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SOURCES } from '../../packages/finops-catalogue/src/index.js'
import {
  resetIds,
  statPanel,
  partialTotalPanel,
  sourcePanel,
  healthPanel,
  runwayPanel,
  poolBalancePanel,
  kpiPanel,
  fxPanel,
  headerPanel,
} from './lib/panels.js'
import { buildAlertRules } from './lib/alerts.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const OUT_DIR = join(ROOT, 'infra/grafana')

const GENERATED_BANNER =
  'GENERATED by scripts/finops/generate-dashboards.js from @fairwins/finops-catalogue. Do not edit by hand — ' +
  'run `npm run finops:generate`. `npm run check:finops` fails when this file is stale.'

/** Grafana's 24-column grid. */
const W = 24
const row = (y, h = 8) => ({ y, h })

function layout() {
  let y = 0
  return {
    /** Full-width block. */
    full(h) {
      const pos = { h, w: W, x: 0, y }
      y += h
      return pos
    },
    /** `n` equal columns on one row. */
    cols(n, h) {
      const w = Math.floor(W / n)
      const out = Array.from({ length: n }, (_, i) => ({ h, w, x: i * w, y }))
      y += h
      return out
    },
  }
}

function buildOverview() {
  resetIds()
  const L = layout()
  const panels = []

  panels.push(
    headerPanel({
      gridPos: L.full(4),
      content: [
        '# FairWins FinOps — overview',
        '',
        'Every figure here carries its own honesty state. **A missing source is never shown as `0`.**',
        '',
        '- **Sources currently MISSING** — if that table has rows, the totals above it are *partial and understated*.',
        '- **(modelled)** in a panel title means the dollar figure is our arithmetic over a declared plan rate, not an invoice.',
        '  Only GCP is `billed`. Cloudflare and QuickNode publish no dollar figure at all (spec 089 research R1).',
        '- **NOT YET LIVE** panels are declared sources with nothing to read. They contribute nothing to any total.',
        '- Freshness differs by source: chain reads are seconds old, the GCP billing export lags hours. See *Source health*.',
      ].join('\n'),
    }),
  )

  // Headline. Per-unit, never cross-unit (contracts/metrics.md).
  const head = L.cols(3, 6)
  panels.push(
    statPanel({
      title: 'Revenue (by unit)',
      description: 'Sum of live revenue sources, per unit. Accrued and waived are deliberately excluded — neither is revenue received.',
      expr: 'sum by (unit) (fairwins_finops_revenue_total)',
      unit: 'short',
      gridPos: head[0],
    }),
    statPanel({
      title: 'Cost (USD, by basis)',
      description: 'Sum of live cost sources, split by basis. `billed` came from an invoice; `modelled` is our arithmetic.',
      expr: 'sum by (basis) (fairwins_finops_cost_usd_total)',
      gridPos: head[1],
    }),
    statPanel({
      title: 'Net (USDC revenue − USD cost)',
      description:
        'A deliberately narrow net: USDC revenue minus total USD cost. It exists only when BOTH sides have data, ' +
        'because a net computed against a missing cost side reads as profit.',
      expr:
        'sum(fairwins_finops_revenue_total{unit="USDC"}) - sum(fairwins_finops_cost_usd_total) ' +
        'and on() (count(fairwins_finops_source_up{kind="cost"} == 1) > 0)',
      gridPos: head[2],
    }),
  )

  const partials = L.cols(2, 6)
  panels.push(partialTotalPanel({ kind: 'revenue', gridPos: partials[0] }))
  panels.push(partialTotalPanel({ kind: 'cost', gridPos: partials[1] }))

  panels.push(healthPanel({ gridPos: L.full(9) }))

  // Prepaid pools — the P1 alerting story.
  const pools = L.cols(2, 8)
  panels.push(runwayPanel({ gridPos: pools[0] }))
  panels.push(poolBalancePanel({ gridPos: pools[1] }))

  // Unit economics (FR-012).
  const kpis = L.cols(2, 5)
  panels.push(
    kpiPanel({
      title: 'Cost per sponsored UserOp (1h)',
      description:
        'Paymaster gas spend divided by sponsored ops over the same window. NOT COMPUTED when either input is ' +
        'unavailable — a ratio built on a missing denominator is a fabricated number, not an estimate.',
      numerator: 'rate(fairwins_finops_cost_usd_total{source="paymaster-gas"}[1h])',
      denominator: 'rate(fairwins_finops_sponsored_ops_total[1h])',
      guardSources: ['paymaster-gas'],
      unit: 'currencyUSD',
      gridPos: kpis[0],
    }),
    kpiPanel({
      title: 'Infra cost per USDC of revenue (24h)',
      description: 'Total modelled + billed infrastructure cost against USDC revenue. Not computed if either side is missing.',
      numerator: 'sum(rate(fairwins_finops_cost_usd_total[24h]))',
      denominator: 'sum(rate(fairwins_finops_revenue_total{unit="USDC"}[24h]))',
      guardSources: ['gcp'],
      unit: 'none',
      gridPos: kpis[1],
    }),
  )

  panels.push(fxPanel({ gridPos: L.full(6) }))

  return dashboard({
    uid: 'fairwins-finops-overview',
    title: 'FairWins FinOps — Overview',
    description: GENERATED_BANNER,
    tags: ['finops', 'generated'],
    panels,
  })
}

function buildDetail(kind) {
  resetIds()
  const L = layout()
  const panels = []
  const label = kind === 'revenue' ? 'Revenue' : kind === 'usage' ? 'Usage' : 'Cost'

  panels.push(
    headerPanel({
      gridPos: L.full(3),
      content:
        `# FairWins FinOps — ${label.toLowerCase()} sources\n\n` +
        `One panel per catalogued ${kind} source. This page is generated from the catalogue, so a source that ` +
        `exists in the platform and not here is a CI failure, not an oversight.`,
    }),
  )

  panels.push(partialTotalPanel({ kind, gridPos: L.full(6) }))

  // ABOVE the per-source panels, not below them. A blank panel sends the reader looking for why,
  // and the answer has to be on the way down rather than past twenty panels they have to scroll
  // through first — which is how the QuickNode and Grafana Cloud panels both read as "no data"
  // with nothing on the page saying that one was broken and the other was never wired.
  panels.push(healthPanel({ kind, gridPos: L.full(8) }))

  // Two per row, in catalogue order.
  const entries = SOURCES.filter((s) => s.kind === kind && s.status !== 'retired')
  for (let i = 0; i < entries.length; i += 2) {
    const cols = L.cols(2, 8)
    panels.push(sourcePanel({ source: entries[i], gridPos: cols[0] }))
    if (entries[i + 1]) panels.push(sourcePanel({ source: entries[i + 1], gridPos: cols[1] }))
  }

  return dashboard({
    uid: `fairwins-finops-${kind}`,
    title: `FairWins FinOps — ${label}`,
    description: GENERATED_BANNER,
    tags: ['finops', 'generated', kind],
    panels,
  })
}

function dashboard({ uid, title, description, tags, panels }) {
  return {
    uid,
    title,
    description,
    tags,
    timezone: 'utc',
    schemaVersion: 39,
    // Never auto-incremented by the generator: the provisioner sends `overwrite: true`, and a
    // version that changed on every run would make the committed file differ from itself.
    version: 1,
    refresh: '1m',
    time: { from: 'now-30d', to: 'now' },
    templating: {
      list: [
        {
          name: 'datasource',
          type: 'datasource',
          query: 'prometheus',
          current: {},
          hide: 0,
          label: 'Data source',
        },
      ],
    },
    panels,
  }
}

// ── write / check ────────────────────────────────────────────────────────────────────────────

const artifacts = [
  ['dashboards/finops-overview.json', buildOverview()],
  ['dashboards/finops-revenue.json', buildDetail('revenue')],
  ['dashboards/finops-cost.json', buildDetail('cost')],
  ['dashboards/finops-usage.json', buildDetail('usage')],
  ['alerts/finops-alerts.json', buildAlertRules(SOURCES)],
]

const checkOnly = process.argv.includes('--check')
let stale = []

for (const [relPath, content] of artifacts) {
  const outPath = join(OUT_DIR, relPath)
  const text = JSON.stringify(content, null, 2) + '\n'

  if (checkOnly) {
    if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== text) stale.push(relPath)
    continue
  }
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, text)
  console.log(`wrote infra/grafana/${relPath}`)
}

if (checkOnly) {
  if (stale.length) {
    console.error('\nFinOps dashboards are STALE:\n')
    for (const f of stale) console.error(`  infra/grafana/${f}`)
    console.error('\nFix: run `npm run finops:generate` and commit the result.')
    console.error('This means the catalogue or the panel builders changed without the committed dashboards')
    console.error('being regenerated — the dashboards would query metrics that no longer match.\n')
    process.exit(1)
  }
  console.log('FinOps dashboards are up to date.')
}

export { buildOverview, buildDetail }
